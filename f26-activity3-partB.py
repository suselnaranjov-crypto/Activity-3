# Convert a temperature from Celsius to Fahrenheit.
# Formula: Fahrenheit = (Celsius * 9 / 5) + 32
# Start with a temperature of 20 degrees Celsius.

# TODO 1: Create a variable for the Celsius temperature and assign it 20.
